window.MAG.search = function (q) {
  q = q.trim().toLowerCase(); if (!q) return [];
  const out = [];
  for (const it of window.MAG.items) {
    const hits = [];
    if (it.title.toLowerCase().includes(q)) hits.push({ where: "Title", text: it.title });
    for (const [at, t] of it.points) if (t.toLowerCase().includes(q)) hits.push({ where: "Key point", at, text: t });
    for (const [at, t] of it.transcript) if (t.toLowerCase().includes(q)) hits.push({ where: "Said", at, text: t });
    if (it.summary.toLowerCase().includes(q)) hits.push({ where: "Summary", text: it.summary });
    for (const t of it.things) if (t.toLowerCase().includes(q)) hits.push({ where: "Mentions", text: t });
    if ((it.caption || "").toLowerCase().includes(q)) hits.push({ where: "Caption", text: it.caption });
    for (const l of it.links || []) if (l.name.toLowerCase().includes(q)) hits.push({ where: "Link", text: l.name + " · " + l.url });
    if (hits.length) out.push({ it, hits });
  }
  return out;
};
window.MAG.mark = function (text, q) {
  const esc = s => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  if (!q) return esc(text);
  const i = text.toLowerCase().indexOf(q.toLowerCase());
  if (i < 0) return esc(text);
  return esc(text.slice(0, i)) + "<mark>" + esc(text.slice(i, i + q.length)) + "</mark>" + esc(text.slice(i + q.length));
};
